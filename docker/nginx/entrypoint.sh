#!/bin/sh
# First-start helper for the nginx container.
# If certs are missing (no setup-vps.sh run, empty volume), mint self-signed
# certs so HTTPS on :443 can bind. Existing files are left alone so a
# container recreate does not rotate the cert — that includes Let's Encrypt
# pems installed by scripts/setup-letsencrypt.sh.
#
# Public (SITE_DOMAIN) and maintenance (SITE_MAINTENANCE_DOMAIN) use separate
# files so Certificate Transparency does not link the two names.
set -eu

CERT_DIR=/etc/nginx/certs
CERT="${CERT_DIR}/fullchain.pem"
KEY="${CERT_DIR}/privkey.pem"
M_CERT="${CERT_DIR}/maintenance-fullchain.pem"
M_KEY="${CERT_DIR}/maintenance-privkey.pem"
HTTPS_CONF="${CERT_DIR}/https-servers.conf"
HAWSER_STREAM_CONF="${CERT_DIR}/hawser-stream.conf"
DOMAIN="${SITE_DOMAIN:-localhost}"
# Prefer SITE_MAINTENANCE_DOMAIN; fall back to first SITE_DOMAIN_ALIASES token.
MAINT="${SITE_MAINTENANCE_DOMAIN:-}"
if [ -z "${MAINT}" ] && [ -n "${SITE_DOMAIN_ALIASES:-}" ]; then
	MAINT=$(printf '%s' "${SITE_DOMAIN_ALIASES}" | tr ',' ' ' | awk '{print $1}')
fi
OT_IP="${OT_IP:-127.0.0.1}"

is_ipv4() {
	echo "$1" | grep -Eq '^[0-9]{1,3}(\.[0-9]{1,3}){3}$'
}

san_entry() {
	if is_ipv4 "$1"; then
		echo "IP:$1"
	else
		echo "DNS:$1"
	fi
}

mint_self_signed() {
	_out="$1"
	_key="$2"
	_cn="$3"
	echo "Generating self-signed certificate for ${_cn}"
	_san="$(san_entry "${_cn}"),$(san_entry localhost),IP:127.0.0.1"
	if [ -n "${OT_IP}" ] && [ "${OT_IP}" != "${_cn}" ] && [ "${OT_IP}" != "localhost" ]; then
		_san="${_san},$(san_entry "${OT_IP}")"
	fi
	openssl req -x509 -nodes -newkey rsa:2048 -days 3650 \
		-keyout "${_key}" \
		-out "${_out}" \
		-subj "/CN=${_cn}" \
		-addext "subjectAltName=${_san}"
	chmod 644 "${_out}"
	chmod 600 "${_key}" || true
}

write_https_servers() {
	# Primary is default_server so unknown Host still gets a valid TLS handshake.
	cat > "${HTTPS_CONF}" <<EOF
# Generated by docker/nginx/entrypoint.sh / install-letsencrypt-certs.sh — do not edit.
server {
    listen 443 ssl default_server;
    http2 on;
    server_name ${DOMAIN};

    ssl_certificate     /etc/nginx/certs/fullchain.pem;
    ssl_certificate_key /etc/nginx/certs/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_session_timeout 1d;
    ssl_session_cache   shared:SSL:10m;

    location / {
        set \$website_upstream website:80;
        proxy_pass http://\$website_upstream;
        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_hide_header Server;
        proxy_hide_header X-Powered-By;
    }
}
EOF
	if [ -n "${MAINT}" ] && [ "${MAINT}" != "${DOMAIN}" ] \
		&& [ -f "${M_CERT}" ] && [ -f "${M_KEY}" ]; then
		cat >> "${HTTPS_CONF}" <<EOF

server {
    listen 443 ssl;
    http2 on;
    server_name ${MAINT};

    ssl_certificate     /etc/nginx/certs/maintenance-fullchain.pem;
    ssl_certificate_key /etc/nginx/certs/maintenance-privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_session_timeout 1d;
    ssl_session_cache   shared:SSL:10m;

    location / {
        set \$website_upstream website:80;
        proxy_pass http://\$website_upstream;
        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_hide_header Server;
        proxy_hide_header X-Powered-By;
    }
}
EOF
	fi
}

# H1: only forward Dockhand TLS when SNI is the maintenance hostname.
write_hawser_stream() {
	_map_line="# no SITE_MAINTENANCE_DOMAIN — refuse all Hawser SNI"
	if [ -n "${MAINT}" ]; then
		_map_line="${MAINT} hawser:2376;"
	fi
	cat > "${HAWSER_STREAM_CONF}" <<EOF
# Generated by docker/nginx/entrypoint.sh — do not edit.
# Empty \$hawser_backend closes the connection (wrong/missing SNI).
map \$ssl_preread_server_name \$hawser_backend {
    default "";
    ${_map_line}
}

server {
    listen 2376;
    ssl_preread on;
    proxy_pass \$hawser_backend;
    proxy_connect_timeout 5s;
    proxy_timeout 1h;
}
EOF
}

mkdir -p "${CERT_DIR}"

if [ ! -f "${CERT}" ] || [ ! -f "${KEY}" ]; then
	mint_self_signed "${CERT}" "${KEY}" "${DOMAIN}"
fi

if [ -n "${MAINT}" ] && [ "${MAINT}" != "${DOMAIN}" ]; then
	if [ ! -f "${M_CERT}" ] || [ ! -f "${M_KEY}" ]; then
		mint_self_signed "${M_CERT}" "${M_KEY}" "${MAINT}"
	fi
fi

write_https_servers
write_hawser_stream

exec nginx -g 'daemon off;'
